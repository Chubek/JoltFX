#!/usr/bin/env python3
"""Generate the private native catalogue from the six shipped .jolt interfaces."""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).parent
TYPES = {"void":0,"i32":1,"i64":2,"u8":3,"u16":4,"u32":5,"u64":6,
         "f32":7,"f64":8,"bool":9,"char":10,"string":11,"list":12,
         "vector":13,"map":14,"set":15,"value":22,"function":23,
         "number":100,"sequence":101}

def generate():
    rows = []
    for group, module in enumerate(["math","graphics","geometry","time","collections","strings"]):
        text = (ROOT / (module + ".jolt")).read_text()
        assert f"(module jolt.{module})" in text
        for line in text.splitlines():
            line = line.split(";;",1)[0].strip()
            if not line.startswith("(intrinsic "):
                continue
            match = re.fullmatch(r"\(intrinsic ([^ ]+) \[([^]]*)\] -> ([^)]+)\)",line)
            assert match, line
            name, args, result = match.groups()
            params=[]; minimum=0; optional=False; variadic=False
            for token in args.split():
                if token == "?": optional=True;continue
                if token == "&": variadic=True;optional=True;continue
                params.append(TYPES[token])
                if not optional: minimum+=1
            assert len(params)<=8
            maximum=32 if variadic else len(params)
            constant=name in ["PI","TWO-PI","HALF-PI","E","SQRT2","SQRT1_2"]
            rows.append(f'{{"jolt.{module}","{name}",{group},{minimum},{maximum},{TYPES[result]},'
                        f'{int(constant)},{int(variadic)},{len(params)},' + '{' + (','.join(map(str,params)) or '0') + '}}')
    return "/* Generated by stdlib/generate.py; do not edit. */\nstatic const std_entry stdlib[] = {\n" + ",\n".join(rows) + "\n};\n"

if __name__ == "__main__":
    pathlib.Path(sys.argv[1]).write_text(generate())
